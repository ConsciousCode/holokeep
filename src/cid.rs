/// Error while reading a CID from bytes.
#[derive(Debug, thiserror::Error)]
pub enum DecodeError {
    /// There were not enough bytes to read the multihash.
    #[error("truncated bytes")]
    Truncated,

    /// Error while parsing.
    #[error("parsing")]
    Parse,

    /// Error while building a multihash from a digest.
    #[error("size of a digest")]
    Size(#[from] SizeError),

    /// Cannot determine CID version.
    #[error("unknown CID version")]
    Version,
}

impl From<varint::Error> for DecodeError {
    fn from(value: varint::Error) -> Self {
        match value {
            varint::Error::Truncated => Self::Truncated,
            varint::Error::Overflow => Self::Parse,
        }
    }
}
impl From<multihash::DecodeError> for DecodeError {
    fn from(value: multihash::DecodeError) -> Self {
        match value {
            multihash::DecodeError::Truncated => Self::Truncated,
            multihash::DecodeError::Parse => Self::Parse,
            multihash::DecodeError::Size(e) => Self::Size(e),
        }
    }
}

/// Error generated by parsing a CID in a string.
#[derive(Debug, thiserror::Error)]
pub enum FromStrError {
    #[error("parsing multibase")]
    Multibase(#[from] multibase::Error),

    #[error("parsing multihash")]
    Multihash(#[from] DecodeError),
}

/// Total enum for the version of a CID.
#[derive(Debug, PartialEq, Eq, Copy, Clone, TryFromPrimitive, IntoPrimitive)]
#[repr(u64)]
pub enum CidVersion {
    V0 = 0,
    V1 = 1,
}

/// The most permissive trait of a Cid which just lets you query
/// version, codec, and hashcode.
pub trait BaseCid {
    /// The version of the CID.
    fn version(&self) -> CidVersion;

    /// Get the multicodec of the CID.
    fn codec(&self) -> u64;

    /// Get the hash function codec of the CID.
    fn hashcode(&self) -> u64;
}

/// Dyn-compatible CID.
pub trait CidRef: BaseCid + fmt::Display {
    /// Get a reference to the digest slice of the CID.
    fn digest_ref(&self) -> &[u8];

    /// Get a reference to the multihash of the CID.
    fn multihash(&self) -> Multihash<&[u8]>;

    /// Get the size of the encoded CID in bytes.
    fn size(&self) -> usize;

    /// Convert the CID into bytes.
    fn to_bytes(&self) -> Vec<u8> {
        let mut buf = Vec::with_capacity(self.size());
        self.encode(&mut buf);
        buf
    }
    
    /// Write the CID to a given buffer.
    fn encode(&self, buf: &mut Vec<u8>);
}

// Test for dyn-compatibility
const _: Option<&dyn CidRef> = None;

/// An IPLD Content IDentifier (CID) with a generic digest backing.
/// As a "full" CID with a well-defined digest backing, this trait allows
/// us to implement constructors.
/// 
/// This is not dyn-compatible, it's intended as a concrete owned type. For
/// dynamic CIDs, see CidRef or AnyCid.
pub trait Cid<D>:
    CidRef +
    TryInto<Cidv0<D>> +
    Into<Cidv1<D>> +
    FromStr
{
    /// Get a reference to the digest of the CID.
    fn digest(&self) -> &D;

    /// Consume the CID to get just its digest.
    fn into_digest(self) -> D;
    
    /// Consume the CID to get its multihash.
    fn into_multihash(self) -> Multihash<D> {
        Multihash::new(self.hashcode(), self.into_digest())
    }
    
    /// Read a CID from a given buffer. Not dyn-compatible.
    fn decode(buf: &[u8]) -> Result<Self, DecodeError>;
}

